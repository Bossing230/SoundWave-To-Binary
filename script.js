// ---------- Core conversion (shared by app + test table) ----------
function convert(freq, amp, n, bits){
  const periodMs = (1 / freq) * 1000;
  const wl = 343 / freq;
  const wlText = wl >= 1 ? wl.toFixed(2) + " m" : (wl * 100).toFixed(1) + " cm";
  const levels = Math.pow(2, bits);
  const rows = [];
  let binaryAll = [];
  for (let i = 0; i < n; i++){
    const time = i * periodMs / n;
    const height = amp * Math.sin(2 * Math.PI * i / n);
    const level = Math.round((height + 1) / 2 * (levels - 1));
    const bin = level.toString(2).padStart(bits, "0");
    rows.push({i: i + 1, time: time.toFixed(2), height: height.toFixed(2), level: level, bin: bin});
    binaryAll.push(bin);
  }
  return {
    periodText: periodMs.toFixed(2) + " ms",
    wlText: wlText,
    rows: rows,
    binaryLine: binaryAll.join(" "),
    totalBits: n * bits
  };
}

function validate(freq, amp, n, bits){
  const msgs = [];
  if (!(freq > 0)) msgs.push("Frequency must be greater than 0.");
  if (amp < 0 || amp > 1) msgs.push("Amplitude must be between 0 and 1.");
  if (!Number.isInteger(n) || n < 2 || n > 64) msgs.push("Samples must be a whole number from 2 to 64.");
  if (!Number.isInteger(bits) || bits < 1 || bits > 8) msgs.push("Bits must be a whole number from 1 to 8.");
  return msgs;
}

// ---------- App UI ----------
const $ = id => document.getElementById(id);

function runConvert(){
  const warn = $("warning");
  const freq = parseFloat($("freq").value);
  const amp  = parseFloat($("amp").value);
  const n    = parseFloat($("samples").value);
  const bits = parseFloat($("bits").value);

  const errs = validate(freq, amp, n, bits);
  if (errs.length){
    warn.style.display = "block";
    warn.innerHTML = "&#9888; " + errs.join("<br>&#9888; ");
    return; // page must not break
  }
  warn.style.display = "none";

  const r = convert(freq, amp, n, bits);

  $("fAmp").textContent = $("amp").value;
  $("fFreq").textContent = $("freq").value + " Hz";
  $("fPeriod").textContent = r.periodText;
  $("fWavelength").textContent = r.wlText;

  const body = $("sampleBody");
  body.innerHTML = "";
  r.rows.forEach(s => {
    const tr = document.createElement("tr");
    tr.innerHTML = `<td>${s.i}</td><td>${s.time}</td><td>${s.height}</td><td>${s.level}</td><td class="bin">${s.bin}</td>`;
    body.appendChild(tr);
  });

  $("binaryLine").textContent = r.binaryLine;
  $("totalBits").innerHTML = "Total bits: <b>" + r.totalBits + "</b> (" + n + " samples × " + bits + " bits)";
  drawWave(r.rows, n);
}

function drawWave(rows, n){
  const cv = $("waveCanvas"), ctx = cv.getContext("2d");
  const W = cv.width, H = cv.height, mid = H / 2;
  ctx.clearRect(0, 0, W, H);
  // axes
  ctx.strokeStyle = "#30363d"; ctx.lineWidth = 1;
  ctx.beginPath(); ctx.moveTo(0, mid); ctx.lineTo(W, mid); ctx.stroke();
  // smooth wave
  ctx.strokeStyle = "#58a6ff"; ctx.lineWidth = 2; ctx.beginPath();
  for (let x = 0; x <= W; x++){
    const t = x / W;
    const y = mid - Math.sin(2 * Math.PI * t) * (mid * 0.8);
    x === 0 ? ctx.moveTo(x, y) : ctx.lineTo(x, y);
  }
  ctx.stroke();
  // sample points
  rows.forEach(s => {
    const x = (s.i - 0.5) / n * W;
    const y = mid - parseFloat(s.height) * (mid * 0.8);
    ctx.fillStyle = "#7ee787";
    ctx.beginPath(); ctx.arc(x, y, 5, 0, Math.PI * 2); ctx.fill();
    ctx.strokeStyle = "#7ee787"; ctx.setLineDash([4, 4]);
    ctx.beginPath(); ctx.moveTo(x, mid); ctx.lineTo(x, y); ctx.stroke();
    ctx.setLineDash([]);
  });
}

$("convertBtn").addEventListener("click", runConvert);

// ---------- Bonus: Play tone ----------
$("playBtn").addEventListener("click", () => {
  const freq = parseFloat($("freq").value);
  if (!(freq > 0) || freq > 20000){ $("warning").style.display = "block"; $("warning").textContent = "⚠ Enter a valid frequency (1–20000 Hz) to play a tone."; return; }
  const ctx = new (window.AudioContext || window.webkitAudioContext)();
  const osc = ctx.createOscillator();
  const gain = ctx.createGain();
  osc.frequency.value = freq;
  gain.gain.setValueAtTime(0.25, ctx.currentTime);
  gain.gain.exponentialRampToValueAtTime(0.001, ctx.currentTime + 1);
  osc.connect(gain); gain.connect(ctx.destination);
  osc.start();
  osc.stop(ctx.currentTime + 1);
});

